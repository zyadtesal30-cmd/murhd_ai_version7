def _b_honors(p):
    g = p['an']['gpa']
    s = '[لائحة] مرتبة الشرف: معدل تراكمي 3.3 فأكثر بشرط ألا تكون قد رسبت في أي مقرر.'
    if g is not None:
        if g >= 3.3 and not p['an']['fail']:
            s += '\n\n✔ إنت دلوقتي في النطاق (معدلك %.3f).' % g
        elif g >= 3.3:
            s += '\n\nمعدلك %.3f كفاية لكن رسوبك في مقرر بيمنعها.' % g
        else:
            s += '\n\nناقصك %.3f لحد 3.3.' % (3.3 - g)
    return s


