def _b_plan10(p):
    mx = max(c.sem for c in E.COURSES)
    per = []
    for k in range(1, mx + 1):
        h = sum(c.cr for c in E.COURSES if c.sem == k and c.kind == 'R')
        per.append('%d:%d' % (k, h))
    return ('الخطة الدراسية المقترحة في اللائحة %d فصول. ساعات الإجباري في كل فصل (الفصل:الساعات): %s.\n'
            'تقدر تشوف مواد أي فصل بسؤالي «مواد الفصل 3» مثلاً.' % (mx, ' • '.join(per)))


def _b_codes(p):
    ex = {}
